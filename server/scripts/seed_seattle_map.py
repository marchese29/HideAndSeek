def main() -> None:
    # Look up existing Seattle TransitDataset
    with session_scope():
        dataset = (
            get_session()
            .scalars(select(TransitDataset).where(TransitDataset.region == 'Seattle'))
            .one_or_none()
        )
        if not dataset:
            print('No TransitDataset found for Seattle. Run import_seattle_gtfs.py first.')
            sys.exit(1)

        # Check idempotency
        existing_map = (
            get_session()
            .scalars(select(GameMap).where(GameMap.transit_dataset_id == dataset.id))
            .one_or_none()
        )
        if existing_map:
            print(
                f'GameMap "{existing_map.name}" already exists for Seattle '
                f'(id={existing_map.id}). Delete the database and re-run to recreate.'
            )
            sys.exit(1)

        dataset_id = dataset.id

    # Build district JSON
    districts = [
        {
            'id': d['id'],
            'name': d['name'],
            'class': d['class'],
            'boundary': _coords_to_geojson_polygon(d['coords']),
        }
        for d in DISTRICTS
    ]

    district_classes = [
        {'district_class': 1, 'label': 'King County Council District'},
    ]

    convention = DistanceConvention.imperial
    size = MapSize.medium

    # Compute district borders (shared edges between adjacent district polygons)
    district_polygons = [(d['id'], d['name'], Polygon(d['coords'])) for d in DISTRICTS]
    borders: list[tuple[str, str, BaseGeometry]] = []
    for (id_a, name_a, poly_a), (id_b, name_b, poly_b) in combinations(district_polygons, 2):
        shared = poly_a.boundary.intersection(poly_b.boundary)
        if shared.is_empty or shared.geom_type == 'Point':
            continue
        stable_id = f'{id_a}--{id_b}'
        name = f'{name_a} / {name_b} border'
        borders.append((stable_id, name, shared))

    print(f'  Computed {len(borders)} district borders')

    # Create the GameMap
    with session_scope() as session:
        game_map = GameMap(
            name='Seattle',
            size=size,
            convention=convention,
            transit_dataset_id=dataset_id,
            boundary=MultiPolygon([Polygon(BOUNDARY_COORDS)]),
            districts=districts,
            district_classes=district_classes,
            default_inventory=get_default_inventory(convention, size),
            tentacle_categories=[
                {'category': 'hospital', 'distance': 1},  # 1 mile (imperial)
            ],
        )
        session.add(game_map)
        session.flush()

        # Create MapFeature + GameMapFeature for each district border
        for stable_id, name, geom in borders:
            feature = MapFeature(
                category=FeatureCategory.admin_division_border,
                stable_id=stable_id,
                name=name,
                shape=geom,
            )
            session.add(feature)
            session.flush()
            session.add(GameMapFeature(game_map_id=game_map.id, map_feature_id=feature.id))

        # Create MapFeature + GameMapFeature for each hospital POI
        for hosp_name, lat, lon, hosp_stable_id in HOSPITALS:
            feature = MapFeature(
                category=FeatureCategory.hospital,
                stable_id=hosp_stable_id,
                name=hosp_name,
                shape=Point(lon, lat),
            )
            session.add(feature)
            session.flush()
            session.add(GameMapFeature(game_map_id=game_map.id, map_feature_id=feature.id))

        map_name = game_map.name
        map_id = game_map.id

    print(f'Created GameMap "{map_name}" (id={map_id})')
    print(f'  Size: {size.value}, Convention: {convention.value}')
    print(f'  Boundary: {len(BOUNDARY_COORDS)} points')
    print(f'  Districts: {len(districts)}')
    print(f'  District border features: {len(borders)}')
    print(f'  Hospital POIs: {len(HOSPITALS)}')
    print('  Tentacle categories: hospital (1 mi)')


if __name__ == '__main__':
    main()
